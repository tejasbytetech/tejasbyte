/** Renders social link icons from an array of URLs */
export function SocialLinks({ urls, size = 30, center }: { urls: string[]; size?: number; center?: boolean }) {
  if (!urls?.length) return null;
  return (
    <div style={{ display: "flex", gap: 6, flexWrap: "wrap", justifyContent: center ? "center" : "flex-start" }}>
      {urls.map((url, i) => {
        const social = detectSocialLink(url);
        return (
          <a key={i} href={url} target="_blank" rel="noopener noreferrer" aria-label={social.label}
            title={social.label}
            style={{
              width: size, height: size, borderRadius: 8,
              border: "1.5px solid #E2E4EA",
              display: "flex", alignItems: "center", justifyContent: "center",
              color: "#6B7280", textDecoration: "none",
              transition: "all .2s",
            }}
            onMouseEnter={e => {
              const a = e.currentTarget as HTMLAnchorElement;
              a.style.borderColor = social.color;
              a.style.color = social.color;
              a.style.background = `${social.color}10`;
            }}
            onMouseLeave={e => {
              const a = e.currentTarget as HTMLAnchorElement;
              a.style.borderColor = "#E2E4EA";
              a.style.color = "#6B7280";
              a.style.background = "transparent";
            }}
          >
            {social.icon}
          </a>
        );
      })}
    </div>
  );
}
